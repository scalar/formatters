// Formats a tree of Java files through the wasm module and compares each result,
// byte for byte, with what the native google-java-format CLI wrote for the same
// file. Driven by conformance.sh, which prepares both trees.
//
// usage: node corpus-check.ts <wasm> <corpus-dir> <reference-dir> <style>
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import type { TeaVmRuntime } from './teavm-runtime'

const [wasmPath, corpusDir, referenceDir, style = 'google'] = process.argv.slice(2)

if (!wasmPath || !corpusDir || !referenceDir) {
  console.error('usage: node corpus-check.ts <wasm> <corpus-dir> <reference-dir> [style]')
  process.exit(2)
}

const here = path.dirname(fileURLToPath(import.meta.url))

// The runtime is generated by the build into target/, so it cannot be imported by a static
// specifier - there is nothing to resolve until the build has run.
const { load }: TeaVmRuntime = await import(pathToFileURL(path.join(here, 'target/wasm/classes.wasm-runtime.js')).href)

const raw = fs.readFileSync(wasmPath)
const { exports } = await load(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength), {})
const format = exports.format

if (!format) {
  console.error(`${wasmPath} exports no format(); it was built from the wrong pom.`)
  process.exit(2)
}

const walk = (dir: string): string[] =>
  fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? walk(path.join(dir, entry.name))
        : entry.name.endsWith('.java')
          ? [path.join(dir, entry.name)]
          : [],
    )

/** The first line that differs, which is enough to recognise a divergence. */
const firstDifference = (actual: string, expected: string): string => {
  const a = actual.split('\n')
  const b = expected.split('\n')
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) return `line ${i + 1}: got ${JSON.stringify(a[i])} want ${JSON.stringify(b[i])}`
  }
  return 'trailing difference'
}

const files = walk(corpusDir).sort()
const failures: [file: string, detail: string][] = []
let identical = 0
let totalMs = 0

for (const file of files) {
  const source = fs.readFileSync(file, 'utf8')
  const expected = fs.readFileSync(path.join(referenceDir, path.relative(corpusDir, file)), 'utf8')
  const started = performance.now()
  const result = format(source, `${style}|1|1|1`)
  totalMs += performance.now() - started

  // The Java side prefixes its result with a status character rather than
  // throwing, because an exception crossing the boundary arrives unreadable.
  if (result[0] === 'E') failures.push([file, result.slice(1).split('\n')[0] ?? ''])
  else if (result.slice(1) === expected) identical++
  else failures.push([file, firstDifference(result.slice(1), expected)])
}

console.log(`${style}: ${identical}/${files.length} byte-identical (${(totalMs / files.length).toFixed(1)} ms/file)`)
for (const [file, detail] of failures.slice(0, 20)) console.log(`  ${file}\n    ${detail}`)
if (failures.length > 20) console.log(`  ... and ${failures.length - 20} more`)
process.exit(failures.length === 0 ? 0 : 1)
